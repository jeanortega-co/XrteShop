import os
import subprocess
import sys
import unittest
from pathlib import Path

from database_backend import (
    CompatRow,
    PostgresDatabase,
    _split_statements,
    translate_sql,
)
from psycopg.pq import TransactionStatus


class FakeConnectionInfo:
    transaction_status = TransactionStatus.IDLE


class FakeCursor:
    def __init__(self, rows=None, rowcount=1):
        self.rows = list(rows or [])
        self.rowcount = rowcount

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        rows = list(self.rows)
        self.rows.clear()
        return rows


class FakeConnection:
    def __init__(self):
        self.info = FakeConnectionInfo()
        self.statements = []
        self.commits = 0

    def execute(self, query, parameters=()):
        self.statements.append((query, parameters))
        if "RETURNING id" in query:
            return FakeCursor([{"id": 42}])
        return FakeCursor()

    def commit(self):
        self.commits += 1
        self.info.transaction_status = TransactionStatus.IDLE


class DatabaseBackendTests(unittest.TestCase):
    def test_application_refuses_an_implicit_sqlite_fallback(self):
        repository_root = Path(__file__).resolve().parents[1]
        environment = os.environ.copy()
        for key in (
            "DATABASE_URL",
            "PEMU_DATABASE_URL",
            "POSTGRES_URL",
            "PEMU_DATABASE",
        ):
            environment[key] = ""
        environment.pop("VERCEL", None)
        environment["PEMU_SKIP_DATABASE_INIT"] = "1"

        result = subprocess.run(
            [sys.executable, "-c", "import app"],
            cwd=repository_root,
            env=environment,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )

        self.assertNotEqual(result.returncode, 0)
        self.assertIn("PEMU_DATABASE con una ruta SQLite explícita", result.stderr)

    def test_translates_sqlite_placeholders_without_changing_quoted_question_marks(self):
        query = translate_sql(
            "SELECT '?' AS literal, name FROM users WHERE email = ? AND note = \"?\""
        )
        self.assertEqual(
            query,
            "SELECT '?' AS literal, name FROM users WHERE email = %s AND note = \"?\"",
        )

    def test_translates_sqlite_schema_types_and_timestamp_defaults(self):
        query = translate_sql(
            "CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, "
            "created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)"
        )
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", query)
        self.assertIn(
            "DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', "
            "'YYYY-MM-DD HH24:MI:SS')",
            query,
        )
        self.assertNotIn("AUTOINCREMENT", query)

    def test_translates_sqlite_datetime_expressions_to_text_comparisons(self):
        query = translate_sql(
            "SELECT id FROM product_interactions "
            "WHERE created_at >= datetime('now', '-30 days')"
        )
        self.assertIn(
            "to_char((CURRENT_TIMESTAMP AT TIME ZONE 'UTC') + INTERVAL '-30 day', "
            "'YYYY-MM-DD HH24:MI:SS')",
            query,
        )
        self.assertNotIn("to_char(to_char(", query)

    def test_translates_ignore_conflicts_and_case_insensitive_sort(self):
        query = translate_sql(
            "INSERT OR IGNORE INTO user_favorites (user_id, product_id) VALUES (?, ?)"
        )
        self.assertIn("INSERT INTO user_favorites", query)
        self.assertTrue(query.endswith("ON CONFLICT DO NOTHING"))
        self.assertEqual(
            translate_sql("SELECT products.name FROM products "
                          "ORDER BY products.name COLLATE NOCASE ASC"),
            "SELECT products.name FROM products ORDER BY LOWER(products.name) ASC",
        )

    def test_compat_row_supports_mapping_and_positional_access(self):
        row = CompatRow({"id": 8, "name": "Ana"})
        self.assertEqual(row["name"], "Ana")
        self.assertEqual(row[0], 8)
        self.assertEqual(dict(row), {"id": 8, "name": "Ana"})

    def test_script_splitter_preserves_semicolons_inside_strings(self):
        statements = _split_statements(
            "CREATE TABLE t (value TEXT DEFAULT 'a;b'); "
            "INSERT INTO t VALUES ('c;d');"
        )
        self.assertEqual(
            statements,
            [
                "CREATE TABLE t (value TEXT DEFAULT 'a;b')",
                "INSERT INTO t VALUES ('c;d')",
            ],
        )

    def test_postgres_insert_supplies_lastrowid_and_serializes_writes(self):
        connection = FakeConnection()
        database = PostgresDatabase(connection)
        cursor = database.execute(
            "INSERT INTO users (name, email) VALUES (?, ?)",
            ("Ana", "ana@example.com"),
        )
        self.assertEqual(cursor.lastrowid, 42)
        self.assertIn(
            ("SELECT id FROM pemu_transaction_lock WHERE id = 1 FOR UPDATE", ()),
            connection.statements,
        )
        self.assertIn(
            (
                "INSERT INTO users (name, email) VALUES (%s, %s) RETURNING id",
                ("Ana", "ana@example.com"),
            ),
            connection.statements,
        )
        self.assertEqual(database.execute("SELECT changes()").fetchone()[0], 1)

    def test_postgres_queries_pass_like_wildcards_as_parameters(self):
        connection = FakeConnection()
        database = PostgresDatabase(connection)

        database.execute(
            """UPDATE products SET active = 0
               WHERE supplier_product_id LIKE ?""",
            ("mock-%",),
        )

        self.assertTrue(
            any(
                " ".join(query.split())
                == "UPDATE products SET active = 0 WHERE supplier_product_id LIKE %s"
                and parameters == ("mock-%",)
                for query, parameters in connection.statements
            )
        )

    def test_postgres_immediate_transaction_restarts_after_read_transaction(self):
        connection = FakeConnection()
        connection.info.transaction_status = TransactionStatus.INTRANS
        database = PostgresDatabase(connection)
        database.execute("BEGIN IMMEDIATE")
        self.assertEqual(connection.commits, 1)
        self.assertEqual(connection.statements[0][0], "BEGIN")
        self.assertEqual(connection.statements[1][0], "SELECT id FROM pemu_transaction_lock WHERE id = 1 FOR UPDATE")


if __name__ == "__main__":
    unittest.main()

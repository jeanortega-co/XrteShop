    const keysBySpanish = {
        'Accesorios': 'accessories', 'Cuidado personal': 'personalCare', 'Electrónica': 'electronics',
        'Hogar': 'home', 'Moda': 'fashion', 'Otros': 'other',
    };
    let language = 'es';
    try {
        language = localStorage.getItem('pemu-language') === 'en' ? 'en' : 'es';
    } catch (error) {
        console.warn('Language preference could not be loaded:', error);
    }

    function t(key, fallback) {
        return translations[language][key] || fallback || key;
    }

    function category(value) {
        return translations[language][keysBySpanish[value]] || value;
    }

    function apply(root = document) {
        document.documentElement.lang = language;
        root.querySelectorAll('[data-i18n]').forEach((element) => {
            element.textContent = t(element.dataset.i18n, element.textContent);
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
            element.placeholder = t(element.dataset.i18nPlaceholder, element.placeholder);
        });
        root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
            element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel, element.getAttribute('aria-label')));
        });
        root.querySelectorAll('[data-i18n-title]').forEach((element) => {
            element.title = t(element.dataset.i18nTitle, element.title);
        });
        const selector = document.getElementById('page-language');
        if (selector) selector.value = language;
    }

    function setLanguage(nextLanguage) {
        language = nextLanguage === 'en' ? 'en' : 'es';
        try {
            localStorage.setItem('pemu-language', language);
        } catch (error) {
            console.warn('Language preference could not be saved:', error);
        }
        apply();
        document.dispatchEvent(new CustomEvent('pemu-language-change', { detail: { language } }));
    }

    document.addEventListener('DOMContentLoaded', () => {
        apply();
        const selector = document.getElementById('page-language');
        selector?.addEventListener('change', () => setLanguage(selector.value));
    });

    window.PemuI18n = { t, category, get language() { return language; }, setLanguage };

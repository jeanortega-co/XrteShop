import re
import sqlite3
from collections.abc import Mapping

try:
    import psycopg
    from psycopg.pq import TransactionStatus
    from psycopg.rows import dict_row
except ImportError:
    psycopg = None
    TransactionStatus = None
    dict_row = None


DATABASE_ERRORS = (sqlite3.Error,) + ((psycopg.Error,) if psycopg else ())
DATABASE_INTEGRITY_ERRORS = (sqlite3.IntegrityError,) + (
    (psycopg.IntegrityError,) if psycopg else ()
)

_INSERT_ID_TABLES = {
    "contact_messages",
    "orders",
    "payment_disputes",
    "payment_refunds",
    "supplier_sync_logs",
    "users",
}
_DATETIME_PATTERN = re.compile(
    r"""datetime\(\s*'now'\s*,\s*'([+-]\d+)\s+
        (seconds?|minutes?|hours?|days?)'\s*\)""",
    re.IGNORECASE | re.VERBOSE,
)
_PRAGMA_COLUMNS_PATTERN = re.compile(
    r"^\s*PRAGMA\s+table_info\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*;?\s*$",
    re.IGNORECASE,
)
_INSERT_TABLE_PATTERN = re.compile(
    r"^\s*INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)\b", re.IGNORECASE
)
_POSTGRES_NOW = "__PEMU_POSTGRES_UTC_NOW__"


class CompatRow(Mapping):
    def __init__(self, values):
        self._values = dict(values)
        self._keys = tuple(values)
        self._ordered_values = tuple(values.values())

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._ordered_values[key]
        return self._values[key]

    def __iter__(self):
        return iter(self._keys)

    def __len__(self):
        return len(self._keys)


class PostgresCursor:
    def __init__(self, cursor=None, returns_lastrowid=False, synthetic_row=None):
        self._cursor = cursor
        self._returns_lastrowid = returns_lastrowid
        self._last_row_id = None
        self._synthetic_row = synthetic_row
        self._synthetic_consumed = False

    @property
    def lastrowid(self):
        if not self._returns_lastrowid:
            return None
        if self._last_row_id is not None:
            return self._last_row_id
        row = self.fetchone()
        if row is not None:
            self._last_row_id = row["id"]
        return self._last_row_id

    @property
    def rowcount(self):
        return self._cursor.rowcount if self._cursor else 0

    def fetchone(self):
        if self._synthetic_row is not None:
            if self._synthetic_consumed:
                return None
            self._synthetic_consumed = True
            return CompatRow(self._synthetic_row)
        row = self._cursor.fetchone()
        return CompatRow(row) if row is not None else None

    def fetchall(self):
        if self._synthetic_row is not None:
            row = self.fetchone()
            return [row] if row is not None else []
        return [CompatRow(row) for row in self._cursor.fetchall()]

    def __iter__(self):
        while True:
            row = self.fetchone()
            if row is None:
                return
            yield row


def _replace_qmark_placeholders(query):
    output = []
    quote_character = None
    index = 0
    while index < len(query):
        character = query[index]
        if quote_character:
            if character == quote_character:
                if index + 1 < len(query) and query[index + 1] == quote_character:
                    output.append('"' if quote_character == "`" else character)
                    output.append(query[index + 1])
                    index += 1
                else:
                    output.append('"' if quote_character == "`" else character)
                    quote_character = None
            else:
                output.append(character)
        elif character in ("'", '"', "`"):
            quote_character = character
            output.append('"' if character == "`" else character)
        elif character == "?":
            output.append("%s")
        else:
            output.append(character)
        index += 1
    return "".join(output)


def translate_sql(query):
    query = str(query).strip()
    ignore_conflicts = bool(
        re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", query, re.IGNORECASE)
    )
    query = re.sub(
        r"\bINSERT\s+OR\s+IGNORE\s+INTO\b",
        "INSERT INTO",
        query,
        flags=re.IGNORECASE,
    )
    query = re.sub(
        r"products\.name\s+COLLATE\s+NOCASE",
        "LOWER(products.name)",
        query,
        flags=re.IGNORECASE,
    )
    query = re.sub(r"\s+COLLATE\s+NOCASE\b", "", query, flags=re.IGNORECASE)
    query = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        query,
        flags=re.IGNORECASE,
    )
    query = re.sub(r"\bAUTOINCREMENT\b", "", query, flags=re.IGNORECASE)
    query = re.sub(r"\bINTEGER\b", "BIGINT", query, flags=re.IGNORECASE)
    query = re.sub(r"\bBLOB\b", "BYTEA", query, flags=re.IGNORECASE)
    query = _DATETIME_PATTERN.sub(
        lambda match: (
            f"to_char({_POSTGRES_NOW} "
            f"+ INTERVAL '{match.group(1)} {match.group(2).rstrip('s')}', "
            "'YYYY-MM-DD HH24:MI:SS')"
        ),
        query,
    )
    query = re.sub(
        r"\bCURRENT_TIMESTAMP\b",
        "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')",
        query,
        flags=re.IGNORECASE,
    )
    query = query.replace(
        _POSTGRES_NOW, "(CURRENT_TIMESTAMP AT TIME ZONE 'UTC')"
    )
    query = _replace_qmark_placeholders(query)
    if ignore_conflicts and not re.search(r"\bON\s+CONFLICT\b", query, re.IGNORECASE):
        query = query.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return query


def _split_statements(script):
    statements = []
    start = 0
    quote_character = None
    index = 0
    while index < len(script):
        character = script[index]
        if quote_character:
            if character == quote_character:
                if index + 1 < len(script) and script[index + 1] == quote_character:
                    index += 1
                else:
                    quote_character = None
        elif character in ("'", '"'):
            quote_character = character
        elif character == ";":
            statement = script[start:index].strip()
            if statement:
                statements.append(statement)
            start = index + 1
        index += 1
    statement = script[start:].strip()
    if statement:
        statements.append(statement)
    return statements


class PostgresDatabase:
    def __init__(self, connection):
        self._connection = connection
        self._last_row_count = 0
        self._writer_lock_acquired = False

    @classmethod
    def connect(cls, database_url):
        if psycopg is None:
            raise RuntimeError(
                "PostgreSQL requiere psycopg; instala las dependencias de requirements.txt."
            )
        return cls(psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10))

    def execute(self, query, parameters=()):
        query = str(query)
        pragma_columns = _PRAGMA_COLUMNS_PATTERN.match(query)
        if re.match(r"^\s*PRAGMA\s+foreign_keys\s*=", query, re.IGNORECASE):
            return PostgresCursor()
        if pragma_columns:
            cursor = self._connection.execute(
                """SELECT column_name AS name
                   FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = %s
                   ORDER BY ordinal_position""",
                (pragma_columns.group(1).lower(),),
            )
            return PostgresCursor(cursor)
        if re.match(r"^\s*SELECT\s+changes\s*\(\s*\)\s*;?\s*$", query, re.IGNORECASE):
            return PostgresCursor(
                synthetic_row={"changes": self._last_row_count}
            )

        is_immediate_begin = bool(
            re.match(r"^\s*BEGIN\s+IMMEDIATE\s*;?\s*$", query, re.IGNORECASE)
        )
        if is_immediate_begin:
            if (
                self._connection.info.transaction_status
                == TransactionStatus.INTRANS
            ):
                self._connection.commit()
            cursor = self._connection.execute("BEGIN")
            self._writer_lock_acquired = False
            self._acquire_writer_lock()
            return PostgresCursor(cursor)
        query = translate_sql(query)

        returns_lastrowid = False
        insert_table = _INSERT_TABLE_PATTERN.match(query)
        if (
            insert_table
            and insert_table.group(1).lower() in _INSERT_ID_TABLES
            and not re.search(r"\bRETURNING\b", query, re.IGNORECASE)
        ):
            query = query.rstrip().rstrip(";") + " RETURNING id"
            returns_lastrowid = True

        if self._is_write(query) and not self._writes_lock_table(query):
            self._acquire_writer_lock()
        cursor = self._connection.execute(query, parameters or ())
        self._last_row_count = cursor.rowcount
        if self._writes_lock_table(query):
            self._writer_lock_acquired = False
        return PostgresCursor(cursor, returns_lastrowid=returns_lastrowid)

    def executemany(self, query, parameters):
        query = translate_sql(query)
        if self._is_write(query) and not self._writes_lock_table(query):
            self._acquire_writer_lock()
        cursor = self._connection.cursor()
        cursor.executemany(query, parameters)
        self._last_row_count = cursor.rowcount
        return PostgresCursor(cursor)

    def executescript(self, script):
        for statement in _split_statements(script):
            self.execute(statement)

    def commit(self):
        self._connection.commit()
        self._writer_lock_acquired = False

    def rollback(self):
        self._connection.rollback()
        self._writer_lock_acquired = False

    def close(self):
        self._connection.close()

    @staticmethod
    def _is_write(query):
        return bool(re.match(r"^\s*(INSERT|UPDATE|DELETE|REPLACE)\b", query, re.IGNORECASE))

    @staticmethod
    def _writes_lock_table(query):
        return bool(
            re.match(
                r"^\s*INSERT\s+INTO\s+pemu_transaction_lock\b",
                query,
                re.IGNORECASE,
            )
        )

    def _acquire_writer_lock(self):
        if self._writer_lock_acquired:
            return
        self._connection.execute(
            "SELECT id FROM pemu_transaction_lock WHERE id = 1 FOR UPDATE"
        )
        self._writer_lock_acquired = True
